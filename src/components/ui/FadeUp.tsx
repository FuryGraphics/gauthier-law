"use client";

import { motion } from "framer-motion";
import type { ReactNode } from "react";

// Scroll-triggered fade-up used by every content section. Reduced-motion users get
// the content without movement via <MotionConfig reducedMotion="user"> in Providers.
export function FadeUp({
  children,
  className,
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 28 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: "0px 0px -80px 0px" }}
      transition={{ duration: 0.7, ease: [0.22, 1, 0.36, 1], delay }}
    >
      {children}
    </motion.div>
  );
}
